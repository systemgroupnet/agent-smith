"""
SQL Reviewer Agent - Review SQL migrations and table operations with MCP Tools

This module provides SQL review agent with MCP tool integration for fetching
external data (GitLab, Jira, Confluence) as needed during the review process.
"""

from typing import Optional
from pydantic import BaseModel

from core.agents.tool_agent import create_review_agent_with_tools
from core.utils.conventions_loader import load_conventions
from dto.general import ReviewResponse


class SqlContext(BaseModel):
    """Context for SQL review"""
    content: str
    diff: str
    file_name: str
    file_path: Optional[str] = None
    jira_task_number: Optional[str] = None
    gitlab_token: Optional[str] = None
    gitlab_url: Optional[str] = None
    source_branch: Optional[str] = None
    project_path: Optional[str] = None


def get_sql_reviewer_prompt(context: SqlContext, conventions: str = "") -> str:
    """Get SQL reviewer system prompt with tool usage instructions."""
    
    # Build additional context information
    context_info = []
    if context.file_path:
        context_info.append(f"File Path: {context.file_path}")
    if context.jira_task_number:
        context_info.append(f"Jira Task: {context.jira_task_number}")
    
    context_section = "\n".join(context_info) if context_info else "No additional context"
    
    return f"""You are an expert database reviewer for the application. Review SQL files (migrations, CREATE TABLE, ALTER TABLE statements) with focus on:

## Critical Review Rules

### 1. Primary Key Format
- **Use this format for primary keys**: `BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY`
- This is the standard primary key definition in our system
- Always use BIGINT for primary keys (not INT or SERIAL)

### 2. Foreign Key Constraints
- **Between tables in the SAME schema**: USE foreign keys (this is required)
- **Between tables in DIFFERENT schemas**: DO NOT use foreign keys (this is forbidden)
- Check that foreign key references are only within the same schema

### 3. Column Ordering (Memory Padding Optimization)
- Columns in CREATE TABLE should be sorted by field size from SMALL to LARGE
- Order: SMALLINT (2 bytes) → INTEGER (4 bytes) → BIGINT (8 bytes) → DECIMAL → TIMESTAMPTZ → TEXT/VARCHAR

### 4. Migration Logic Errors
- Check for syntax errors, constraint conflicts, circular dependencies
- Verify proper use of NOT NULL on columns with existing data

### 5. Table Normalization
- Check for data redundancy and normalization violations (1NF, 2NF, 3NF)

## Severity Levels
- **high**: Bugs, errors, data corruption risk, foreign key between schemas, migration errors, wrong data types
- **medium**: Performance concerns, minor normalization issues
- **low**: Style issues, minor suggestions

**CRITICAL**: For EVERY high severity issue, explain WHY it's critical and the potential impact.

## TOOLS AVAILABLE
You have access to MCP tools for GitLab, Jira, and Confluence that can help you:
- Fetch related migration files from the repository
- Look up Jira issues for context about the database changes
- View Confluence documentation about database schema
- Understand the broader context of the migration

Use these tools if you need additional context to perform your review, but avoid unnecessary tool calls.

## Constraints
- EVERY issue MUST have a valid integer line number
- Include file_name in every issue
- Focus ONLY on the 5 main rules above
- DO NOT comment on indexes, documentation, or audit columns (created_by, updated_at, etc.)

=== Project Conventions ===
{conventions if conventions else "No specific conventions defined for this file type."}

=== Context Information ===
{context_section}

=== File Content ===
```
{context.content}
```

=== Git Diff ===
```
{context.diff}
```"""


async def create_sql_reviewer_agent():
    """
    Create SQL reviewer agent with MCP tools.
    
    The agent can use GitLab, Jira, and Confluence tools to fetch additional context.
    """
    return await create_review_agent_with_tools(
        system_prompt="",  # Will be replaced with context-specific prompt
        tools=["gitlab", "atlassian"],  # GitLab + Atlassian (Jira/Confluence) tools
        model_name="gpt-4o",
        temperature=0.0,
        max_iterations=10,
        verbose=False,
    )


async def run_sql_review(context: SqlContext) -> ReviewResponse:
    """
    Run SQL review with MCP tools.
    
    The agent will automatically use MCP tools if it needs additional
    context about the database changes.
    
    Args:
        context: SQL context with file information
        
    Returns:
        ReviewResponse with identified issues
    """
    print(f"  🔍 Running SQL review...")
    
    try:
        # Load conventions
        conventions_text = ""
        if (context.file_path and context.gitlab_url and context.project_path 
            and context.source_branch and context.gitlab_token):
            try:
                conventions_text = await load_conventions(
                    agent_type="sql",
                    file_path=context.file_path,
                    module_name=None,  # SQL files typically don't have module context
                    gitlab_url=context.gitlab_url,
                    project_path=context.project_path,
                    source_branch=context.source_branch,
                    gitlab_token=context.gitlab_token
                )
            except Exception as conv_error:
                print(f"  ⚠️  Warning: Failed to load conventions: {conv_error}")
                conventions_text = ""
        
        # Create agent with tools
        agent = await create_sql_reviewer_agent()
        
        # Build input with context and conventions
        input_text = get_sql_reviewer_prompt(context, conventions_text)
        
        # Run agent
        result = await agent.run(input_text)
        
        print(f"  ✅ SQL review complete: {len(result.issues)} issues found")
        return result
        
    except Exception as e:
        print(f"  ❌ SQL review failed: {e}")
        import traceback
        print(f"     Traceback: {traceback.format_exc()}")
        # Return empty response on error
        return ReviewResponse(issues=[])

